-- Show nutrition records by category
SELECT c.category_name, COUNT(hn.nutrition_id) as nutrition_count
FROM CATEGORY c
JOIN Belong_to bt ON c.category_id = bt.category_id
JOIN has_nutrition hn ON bt.food_id = hn.food_id
GROUP BY c.category_name
ORDER BY c.category_name;

-- Show sample nutrition data with food names
SELECT f.food_name, c.category_name, n.measure, n.calories, n.protein, n.fat, n.carbs
FROM FOOD f
JOIN Belong_to bt ON f.food_id = bt.food_id
JOIN CATEGORY c ON bt.category_id = c.category_id
JOIN has_nutrition hn ON f.food_id = hn.food_id
JOIN NUTRITION n ON hn.nutrition_id = n.nutrition_id
ORDER BY c.category_name, f.food_name
LIMIT 20;

-- Show foods with multiple serving sizes
SELECT f.food_name, COUNT(n.nutrition_id) as serving_sizes
FROM FOOD f
JOIN has_nutrition hn ON f.food_id = hn.food_id
JOIN NUTRITION n ON hn.nutrition_id = n.nutrition_id
GROUP BY f.food_name
HAVING COUNT(n.nutrition_id) > 1
ORDER BY serving_sizes DESC;

